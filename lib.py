def kr(pratyaya, extra=""):
    """Indeclinable primary derivative (क्त्वा / ल्यप् / तुमुन्)."""
    rule = {"क्त्वा": "समानकर्तृकयोः पूर्वकाले",
            "ल्यप्": "समासेऽनञ्पूर्वे क्त्वो ल्यप्",
            "तुमुन्": "तुमुन्ण्वुलौ क्रियायां क्रियार्थायाम्"}.get(pratyaya, "")
    s = f"कृदन्तम् अव्ययम् — कृत्-प्रत्ययः «{pratyaya}» ({rule}); क्त्वातोसुन्कसुनः इति अव्ययसंज्ञा"
    if extra:
        s += f"; {extra}"
    return s


